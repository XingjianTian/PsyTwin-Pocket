  // 初始化日记数据
  initDiaryData() {
    const today = new Date();
    const todayStr = this.formatDateToStr(today);
    const year = today.getFullYear();
    const month = today.getMonth() + 1;

    // 1. 从本地存储加载日记
    const diaryDataMap = this.loadDiaryFromStorage();

    // 2. 清理历史 fallback 日记：只保留 aiGenerated === true 的条目
    // 同时删除今天之前的空日期（没有真实日记的历史日期直接显示为空）
    Object.keys(diaryDataMap).forEach((dateStr) => {
      const entries = diaryDataMap[dateStr];
      if (Array.isArray(entries)) {
        // 只保留 AI 生成的真实日记
        diaryDataMap[dateStr] = entries.filter((e) => e.aiGenerated === true);
        // 如果过滤后为空且不是今天，删除该日期键
        if (diaryDataMap[dateStr].length === 0 && dateStr !== todayStr) {
          delete diaryDataMap[dateStr];
        }
      }
    });

    // 3. 今天的日记：确保有数组（可能是空的）
    if (!diaryDataMap[todayStr]) {
      diaryDataMap[todayStr] = [];
    }

    // 4. 写回存储（清理后的数据）
    wx.setStorageSync('petDiaryMap', diaryDataMap);

    this.setData({
      diarySelectedDate: todayStr,
      diaryDataMap,
      diaryEntries: diaryDataMap[todayStr] || [],
      diaryLoading: false,
      currentYear: year,
      currentMonth: month,
      selectedDateText: this.formatDateText(todayStr),
      selectedDateWeekday: this.getWeekdayText(todayStr),
    }, () => {
      this.generateCalendarDays(year, month);
    });
  },

  // 生成日历天数
  generateCalendarDays(year, month) {
    const firstDay = new Date(year, month - 1, 1);
    const lastDay = new Date(year, month, 0);
    const daysInMonth = lastDay.getDate();
    const startWeekday = firstDay.getDay(); // 0 = 周日

    const { diaryDataMap, diarySelectedDate } = this.data;
    const today = this.formatDateToStr(new Date());
    const days = [];

    // 上个月的日期
    const prevMonthLastDay = new Date(year, month - 1, 0).getDate();
    for (let i = startWeekday - 1; i >= 0; i--) {
      const day = prevMonthLastDay - i;
      const date = new Date(year, month - 2, day);
      const dateStr = this.formatDateToStr(date);
      days.push({
        date: dateStr,
        day: day,
        isCurrentMonth: false,
        isToday: dateStr === today,
        hasEntry: diaryDataMap[dateStr] && diaryDataMap[dateStr].length > 0,
      });
    }

    // 当前月的日期
    for (let i = 1; i <= daysInMonth; i++) {
      const date = new Date(year, month - 1, i);
      const dateStr = this.formatDateToStr(date);
      days.push({
        date: dateStr,
        day: i,
        isCurrentMonth: true,
        isToday: dateStr === today,
        hasEntry: diaryDataMap[dateStr] && diaryDataMap[dateStr].length > 0,
      });
    }

    // 下个月的日期
    const remaining = (7 - (days.length % 7)) % 7;
    for (let i = 1; i <= remaining; i++) {
      const date = new Date(year, month, i);
      const dateStr = this.formatDateToStr(date);
      days.push({
        date: dateStr,
        day: i,
        isCurrentMonth: false,
        isToday: dateStr === today,
        hasEntry: diaryDataMap[dateStr] && diaryDataMap[dateStr].length > 0,
      });
    }

    this.setData({
      calendarDays: days,
    });
    // 更新当前周显示
    this.updateCalendarWeekDays(days);
  },

  // 更新当前周显示（用于折叠状态）
  updateCalendarWeekDays(days) {
    const { diarySelectedDate } = this.data;
    let selectedIndex;

    if (diarySelectedDate) {
      selectedIndex = days.findIndex((d) => d.date === diarySelectedDate);
    } else {
      // 默认显示今天所在周
      const today = this.formatDateToStr(new Date());
      selectedIndex = days.findIndex((d) => d.date === today);
    }

    if (selectedIndex === -1) selectedIndex = 0;

    const weekStart = Math.floor(selectedIndex / 7) * 7;
    const weekDays = days.slice(weekStart, weekStart + 7);

    this.setData({
      calendarWeekDays: weekDays,
    });
  },

